const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string } | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [mounted, setMounted] = useState(false);
  useEffect(() => {
    setMounted(true);
    const saved = localStorage.getItem("gv_lang") as Lang | null;
    if (saved && DICTS[saved]) {
      setLangState(saved);
      document.documentElement.lang = saved;
    } else {
      const browser = navigator.language.slice(0, 2) as Lang;
      if (DICTS[browser]) {
        setLangState(browser);
        document.documentElement.lang = browser;
      }
    }
  }, []);
  useEffect(() => {
    if (mounted) document.documentElement.lang = lang;
  }, [lang, mounted]);
  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("gv_lang", l);
    document.documentElement.lang = l;
  };
  const t = (k: string) => DICTS[lang]?.[k] || DICTS.en[k] || k;
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useLang = () => {
  const v = useContext(Ctx);
  if (!v) throw new Error("useLang outside provider");
  return v;
};

export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { lang, setLang } = useLang();
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);
  const cur = LANGS.find((l) => l.value === lang) || LANGS[0];
  useEffect(() => {
    const h = (e: MouseEvent) => {
      if (ref.current && !ref.current.contains(e.target as Node)) setOpen(false);
    };
    document.addEventListener("mousedown", h);
    return () => document.removeEventListener("mousedown", h);
  }, []);
  return (
    <div ref={ref} className={`relative ${className}`}>
      <button
        onClick={() => setOpen((v) => !v)}
        className="flex items-center gap-1.5 px-3 py-1.5 rounded-full border border-zinc-200 bg-white text-xs font-medium hover:bg-zinc-50 shadow-sm"
        aria-label="Language"
      >
        <span className="w-6 h-6 rounded-full bg-teal-600 text-white grid place-items-center text-[11px] font-bold">{cur.native.slice(0, 1)}</span>
        <span className="hidden sm:inline">{cur.native}</span>
        <span className="text-zinc-400">▼</span>
      </button>
      {open && (
        <div className="absolute right-0 mt-2 w-48 rounded-xl border border-zinc-200 bg-white shadow-[0_12px_32px_rgba(0,0,0,0.12)] overflow-hidden z-50">
          {LANGS.map((l) => (
            <button
              key={l.value}
              onClick={() => {
                setLang(l.value);
                setOpen(false);
              }}
              className={`w-full flex items-center gap-2 px-3 py-2.5 text-sm text-left hover:bg-zinc-50 ${lang === l.value ? "bg-zinc-900 text-white" : ""}`}
            >
              <span className="flex-1">
                <span className="font-medium">{l.native}</span> <span className="text-xs opacity-60">— {l.label}</span>
              </span>
              {lang === l.value && <span>✓</span>}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
