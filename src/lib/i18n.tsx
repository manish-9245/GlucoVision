const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string } | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = (typeof window !== "undefined" ? (localStorage.getItem("gv_lang") as Lang | null) : null) || "en";
    if (saved && DICTS[saved]) setLangState(saved);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("gv_lang", l);
  };
  const t = (k: string) => DICTS[lang]?.[k] || DICTS.en[k] || k;
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useLang = () => {
  const v = useContext(Ctx);
  if (!v) throw new Error("useLang outside provider");
  return v;
};

export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { lang, setLang } = useLang();
  return (
    <select
      value={lang}
      onChange={(e) => setLang(e.target.value as Lang)}
      className={`px-2 py-1.5 rounded-full border border-zinc-200 bg-white text-xs font-medium ${className}`}
      aria-label="Language"
    >
      {LANGS.map((l) => (
        <option key={l.value} value={l.value}>
          {l.native} — {l.label}
        </option>
      ))}
    </select>
  );
}
